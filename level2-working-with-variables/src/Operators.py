# 2. Shortcut Assignment Operators

# Normal assignment:

# Addition Assignment (+=)
x = 5
x = x + 1
print(x)
# Shortcut assignment:

x = 5
x += 1
print(x)

# Subtraction Assignment (-=)
x = 10
x -= 5
print(x)

# Multiplication Assignment (*=)
x = 2
x *= 3
print(x)

# Division Assignment (/=)
x = 10
x /= 2
print(x)

# Exponentiation Assignment (**=)
x = 2
x **= 3
print(x)

# Modulo Assignment (%=)
x = 15
x %= 3
print(x)

# 3. Comparison Operators

# Equality (==)
x = 5
y = 5
print(x == y)

# Inequality (!=)
x = 5
y = 3
print(x != y)

# Greater than (>)
x = 5
y = 3
print(x > y)

# Less than (<)
x = 3
y = 5
print(x < y)

# Greater than or equal to (>=)
x = 5
y = 5
print(x >= y)

# Less than or equal to (<=)
x = 5
y = 6
print(x <= y)

# 4. Logical Operators

# AND (and)
x = True
y = True
print(x and y)

# OR (or)
x = False
y = True
print(x or y)

# NOT (not)
x = True
print(not x)

# 5. Identity Operators

# Is (is)
x = 5
y = 5
